"""Response-diff harness: replay the `/v1` GET corpus against the TS and the Python API and diff the answers.

    uv run python scripts/parity.py --start [--out parity-report.json]
    uv run python scripts/parity.py --ts-url http://127.0.0.1:4214 --py-url http://127.0.0.1:4114

With `--start` the harness seeds a source database with `command-inbox-seed` (clock pinned to the current
minute), clones it twice (`ci_parity_ts`, `ci_parity_py`) and starts both servers itself on ports 4214 (TS)
and 4114 (Python); it stops them when it is done. Without it, it targets servers that are already running
on two copies of the same seeded database.

Each demo user (staff, lead, admin) signs in on both servers with POST /v1/auth/login. The corpus covers
every GET route in apps/server/src/routes/*.ts; ids come from the TS responses (both databases are clones,
so ids agree). Volatile fields are normalised before diffing: CSRF tokens, request ids, session ids, and
timestamps that differ by under two seconds (created at sign-in, a moment apart on each server).

The report lists, per request, both status codes and the differing JSON paths, and a coverage summary per
route: identical, differing, or missing (the Python API answers 404/405 where the TS API does not).
"""

